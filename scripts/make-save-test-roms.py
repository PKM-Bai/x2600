"""Build original ARM7TDMI battery-save diagnostics without a cross compiler.

These ROMs never write backup data merely by booting. A or B press edges write
different markers and increment the persisted counter. The entire save consists
of repeated little-endian <marker, counter> records, so the host can compare every
byte. FLASH commands and EEPROM bit streams are generated by the guest CPU.

Mailbox at 0x02000000 (32-bit little-endian words): see MAILBOX_FIELDS below.
state: 0=blank, 1=valid A, 2=valid B, 3=invalid, 4=writing. The screen is respectively
blue, green, cyan, red, or yellow. boot_marker/boot_count remain unchanged after
startup, while marker/count report the most recent read-back.
"""

import argparse
from pathlib import Path
import struct


KINDS = {"sram": (1, 32768), "flash": (2, 65536), "eeprom": (3, 512)}
MARKERS = {"A": 0x53415641, "B": 0x53415642}
MAILBOX_ADDRESS = 0x02000000
MAILBOX_MAGIC = 0x53565453
MAILBOX_FIELDS = (
    "magic", "kind", "capacity", "state", "marker", "count",
    "expected_marker", "expected_count", "mismatch_offset", "write_events",
    "frames", "keys", "boot_marker", "boot_count", "last_action", "checks",
)


def expected_save(kind, marker="A", count=1):
    """Return the complete expected battery image after a successful write."""
    capacity = KINDS[kind][1]
    if isinstance(marker, str):
        marker = MARKERS[marker.upper()]
    return struct.pack("<II", marker, count) * (capacity // 8)


class _Arm:
    """Small encoder for only the ARM instructions used by these diagnostics."""

    def __init__(self):
        self.words = []
        self.labels = {}
        self.branches = []
        self.literals = []

    @property
    def pos(self):
        return 0xC0 + len(self.words) * 4

    def emit(self, value):
        self.words.append(value)

    def label(self, name):
        assert name not in self.labels
        self.labels[name] = self.pos

    def branch(self, name, cond=14, link=False):
        self.branches.append((len(self.words), name, cond, link))
        self.emit(0)

    def literal(self, reg, value):
        self.literals.append((len(self.words), reg, value))
        self.emit(0)

    def dp(self, opcode, dst, src, operand, *, immediate=False, flags=False,
           cond=14, shift=0, shift_type=0, shift_reg=None):
        if immediate:
            # Rotate an 8-bit immediate right by an even number of bits.
            for rotate in range(16):
                amount = rotate * 2
                encoded = ((operand << amount) |
                           (operand >> (32 - amount if amount else 32))) & 0xFFFFFFFF
                if encoded <= 255:
                    op2 = (rotate << 8) | encoded
                    break
            else:
                raise ValueError(f"ARM immediate cannot encode {operand:#x}")
        else:
            op2 = operand | (shift_type << 5)
            if shift_reg is not None:
                op2 |= (shift_reg << 8) | 0x10
            else:
                op2 |= shift << 7
        self.emit((cond << 28) | (int(immediate) << 25) | (opcode << 21) |
                  (int(flags) << 20) | (src << 16) | (dst << 12) | op2)

    def mov(self, dst, value, cond=14):
        self.dp(13, dst, 0, value, immediate=True, cond=cond)

    def mov_reg(self, dst, src, **kwargs):
        self.dp(13, dst, 0, src, **kwargs)

    def cmp(self, src, value):
        self.dp(10, 0, src, value, immediate=True, flags=True)

    def cmp_reg(self, src, value):
        self.dp(10, 0, src, value, flags=True)

    def add(self, dst, src, value):
        self.dp(4, dst, src, value, immediate=True)

    def sub(self, dst, src, value, flags=False):
        self.dp(2, dst, src, value, immediate=True, flags=flags)

    def mem(self, load, reg, base, offset=0, *, byte=False, post=False):
        assert 0 <= offset <= 4095
        self.emit(0xE4000000 | (int(not post) << 24) | (1 << 23) |
                  (int(byte) << 22) | (int(load) << 20) | (base << 16) |
                  (reg << 12) | offset)

    def half(self, load, reg, base, offset=0, *, post=False):
        assert 0 <= offset <= 255
        self.emit(0xE04000B0 | (int(not post) << 24) | (1 << 23) |
                  (int(load) << 20) | (base << 16) | (reg << 12) |
                  ((offset & 0xF0) << 4) | (offset & 15))

    def push(self, mask):
        self.emit(0xE92D0000 | mask)

    def pop(self, mask):
        self.emit(0xE8BD0000 | mask)

    def ret(self):
        self.emit(0xE12FFF1E)

    def finish(self):
        for index, name, cond, link in self.branches:
            delta = (self.labels[name] - (0xC0 + index * 4 + 8)) // 4
            assert -(1 << 23) <= delta < (1 << 23)
            self.words[index] = (cond << 28) | 0x0A000000 | (int(link) << 24) | (delta & 0xFFFFFF)
        pool = {}
        for index, reg, value in self.literals:
            if value not in pool:
                pool[value] = self.pos
                self.emit(value)
            delta = pool[value] - (0xC0 + index * 4 + 8)
            assert 0 <= delta <= 4095
            self.words[index] = 0xE59F0000 | (reg << 12) | delta
        return struct.pack("<" + "I" * len(self.words), *self.words)


def _eeprom_dma(a):
    """Use DMA3's actual transaction length to address a 512-byte EEPROM."""
    tx, rx, device = 0x02001400, 0x02001600, 0x0DFFFF00
    for reading in (True, False):
        prefix = "eeprom_read" if reading else "eeprom_write"
        a.label(prefix)
        a.push(sum(1 << r for r in (4, 5, 6, 7, 14)))
        a.mov_reg(6, 0)  # six-bit block address
        a.mov_reg(5, 1)  # eight-byte payload
        a.literal(4, tx)
        a.mov(0, 1)
        a.half(False, 0, 4, 2, post=True)
        a.mov(0, int(reading))
        a.half(False, 0, 4, 2, post=True)
        a.mov(7, 5)
        a.label(prefix + "_address")
        a.mov_reg(0, 6, shift_type=1, shift_reg=7)
        a.dp(0, 0, 0, 1, immediate=True)
        a.half(False, 0, 4, 2, post=True)
        a.sub(7, 7, 1, flags=True)
        a.branch(prefix + "_address", cond=5)
        if not reading:
            a.mov(6, 8)
            a.label(prefix + "_pack_byte")
            a.mem(True, 2, 5, 1, byte=True, post=True)
            a.mov(7, 8)
            a.label(prefix + "_pack_bit")
            a.mov_reg(0, 2, shift=7, shift_type=1)
            a.dp(0, 0, 0, 1, immediate=True)
            a.half(False, 0, 4, 2, post=True)
            a.mov_reg(2, 2, shift=1)
            a.sub(7, 7, 1, flags=True)
            a.branch(prefix + "_pack_bit", cond=1)
            a.sub(6, 6, 1, flags=True)
            a.branch(prefix + "_pack_byte", cond=1)
        a.mov(0, 0)  # final stop bit
        a.half(False, 0, 4)
        a.literal(0, tx)
        a.literal(1, device)
        # Enable immediate 16-bit DMA3, increment source, fixed destination.
        a.literal(2, 0x80400000 | (9 if reading else 73))
        a.branch("eeprom_dma_transfer", link=True)
        if reading:
            a.literal(0, device)
            a.literal(1, rx)
            # Four dummy bits and 64 data bits, fixed source, increment dest.
            a.literal(2, 0x81000044)
            a.branch("eeprom_dma_transfer", link=True)
            a.literal(4, rx + 8)
            a.mov(6, 8)
            a.label(prefix + "_unpack_byte")
            a.mov(2, 0)
            a.mov(7, 8)
            a.label(prefix + "_unpack_bit")
            a.half(True, 0, 4, 2, post=True)
            a.dp(0, 0, 0, 1, immediate=True)
            a.mov_reg(2, 2, shift=1)
            a.dp(12, 2, 2, 0)
            a.sub(7, 7, 1, flags=True)
            a.branch(prefix + "_unpack_bit", cond=1)
            a.mem(False, 2, 5, 1, byte=True, post=True)
            a.sub(6, 6, 1, flags=True)
            a.branch(prefix + "_unpack_byte", cond=1)
        else:
            a.literal(4, device)
            a.label(prefix + "_ready")
            a.half(True, 0, 4)
            a.dp(8, 0, 0, 1, immediate=True, flags=True)
            a.branch(prefix + "_ready", cond=0)
        a.pop(sum(1 << r for r in (4, 5, 6, 7, 15)))

    a.label("eeprom_dma_transfer")
    a.literal(3, 0x040000D4)  # DMA3 source/destination/count+control
    a.mem(False, 0, 3)
    a.mem(False, 1, 3, 4)
    a.mem(False, 2, 3, 8)
    # Allow the enable write to take effect before polling completion.
    a.mov_reg(0, 0)
    a.mov_reg(0, 0)
    a.label("eeprom_dma_wait")
    a.half(True, 0, 3, 10)
    a.dp(8, 0, 0, 0x8000, immediate=True, flags=True)
    a.branch("eeprom_dma_wait", cond=1)
    a.ret()


def save_test_rom(kind, *, eeprom_dma=False, flash_poll=False):
    """Create a 32KiB original diagnostic for sram, flash, or eeprom."""
    kind_id, capacity = KINDS[kind]
    a = _Arm()
    # r8=mailbox, r9=full backup scratch buffer, r10=capacity, r11=IO base.
    a.literal(13, 0x03007F00)
    a.literal(8, MAILBOX_ADDRESS)
    a.literal(9, 0x02001000)
    a.literal(10, capacity)
    a.literal(11, 0x04000000)
    a.mov(0, 0)
    for field in range(len(MAILBOX_FIELDS)):
        a.mem(False, 0, 8, field * 4)
    a.literal(0, MAILBOX_MAGIC)
    a.mem(False, 0, 8)
    a.mov(0, kind_id)
    a.mem(False, 0, 8, 4)
    a.mem(False, 10, 8, 8)
    a.literal(0, 0x0403)  # mode 3 + BG2
    a.half(False, 0, 11)
    if kind == "flash":
        # Establish FLASH on a new blank image without changing backup bytes.
        a.mov(0, 0x90)
        a.branch("flash_command", link=True)
        a.mov(0, 0xF0)
        a.branch("flash_command", link=True)
    a.branch("read_all", link=True)
    a.branch("verify", link=True)
    a.mem(True, 0, 8, 16)
    a.mem(False, 0, 8, 48)
    a.mem(True, 0, 8, 20)
    a.mem(False, 0, 8, 52)
    a.branch("paint", link=True)
    a.label("frame")
    # Wait for a complete next VBlank without relying on an IRQ vector/BIOS.
    a.label("wait_visible")
    a.half(True, 0, 11, 6)
    a.cmp(0, 160)
    a.branch("wait_visible", cond=10)  # GE
    a.label("wait_vblank")
    a.half(True, 0, 11, 6)
    a.cmp(0, 160)
    a.branch("wait_vblank", cond=11)  # LT
    a.mem(True, 0, 8, 40)
    a.add(0, 0, 1)
    a.mem(False, 0, 8, 40)
    a.literal(0, 0x04000130)
    a.half(True, 0, 0)
    a.dp(15, 0, 0, 0)  # mvn r0,r0
    a.dp(0, 0, 0, 3, immediate=True)
    a.mem(True, 1, 8, 44)
    a.mem(False, 0, 8, 44)
    a.dp(14, 2, 0, 1)  # new presses = current & ~previous
    a.dp(8, 0, 2, 1, immediate=True, flags=True)
    a.branch("press_a", cond=1)
    a.dp(8, 0, 2, 2, immediate=True, flags=True)
    a.branch("press_b", cond=1)
    a.branch("frame")
    a.label("press_a")
    a.literal(0, MARKERS["A"])
    a.mov(1, 1)
    a.branch("write_action", link=True)
    a.branch("frame")
    a.label("press_b")
    a.literal(0, MARKERS["B"])
    a.mov(1, 2)
    a.branch("write_action", link=True)
    a.branch("frame")

    a.label("write_action")
    a.push((1 << 4) | (1 << 5) | (1 << 14))
    a.mov_reg(4, 0)
    a.mem(False, 1, 8, 56)
    a.mem(True, 2, 8, 12)
    a.mov(5, 0)
    a.cmp(2, 1)
    a.mem(True, 5, 8, 20)  # load below is unconditional; clear if not valid
    a.branch("valid_counter", cond=0)
    a.cmp(2, 2)
    a.branch("valid_counter", cond=0)
    a.mov(5, 0)
    a.label("valid_counter")
    a.add(5, 5, 1)
    a.mem(False, 4, 8, 24)
    a.mem(False, 5, 8, 28)
    a.mov(0, 4)
    a.mem(False, 0, 8, 12)
    a.branch("paint", link=True)
    a.mov_reg(0, 9)
    a.mov_reg(1, 10)
    a.label("fill_buffer")
    a.mem(False, 4, 0, 4, post=True)
    a.mem(False, 5, 0, 4, post=True)
    a.sub(1, 1, 8, flags=True)
    a.branch("fill_buffer", cond=1)
    a.branch("write_all", link=True)
    a.branch("read_all", link=True)
    a.branch("verify", link=True)
    a.mem(True, 0, 8, 36)
    a.add(0, 0, 1)
    a.mem(False, 0, 8, 36)
    a.branch("paint", link=True)
    a.pop((1 << 4) | (1 << 5) | (1 << 15))

    a.label("verify")
    a.push((1 << 4) | (1 << 5) | (1 << 6) | (1 << 14))
    a.mem(True, 4, 9)
    a.mem(True, 5, 9, 4)
    a.mem(False, 4, 8, 16)
    a.mem(False, 5, 8, 20)
    a.mem(True, 0, 8, 12)
    a.cmp(0, 4)
    a.branch("keep_expected", cond=0)
    a.mem(False, 4, 8, 24)
    a.mem(False, 5, 8, 28)
    a.label("keep_expected")
    a.mov(6, 3)
    a.literal(0, MARKERS["A"])
    a.cmp_reg(4, 0)
    a.mov(6, 1, cond=0)
    a.literal(0, MARKERS["B"])
    a.cmp_reg(4, 0)
    a.mov(6, 2, cond=0)
    a.dp(15, 0, 0, 0, immediate=True)  # -1
    a.cmp_reg(4, 0)
    a.branch("check_count", cond=1)
    a.cmp_reg(5, 0)
    a.mov(6, 0, cond=0)
    a.label("check_count")
    a.mov_reg(1, 9)
    a.mov(2, 0)
    a.mem(False, 0, 8, 32)  # -1 means every record matched
    a.label("verify_record")
    a.mem(True, 3, 1, 4, post=True)
    a.cmp_reg(3, 4)
    a.branch("mismatch", cond=1)
    a.add(2, 2, 4)
    a.mem(True, 3, 1, 4, post=True)
    a.cmp_reg(3, 5)
    a.branch("mismatch", cond=1)
    a.add(2, 2, 4)
    a.cmp_reg(2, 10)
    a.branch("verify_record", cond=3)  # LO
    a.mem(True, 0, 8, 24)
    a.cmp_reg(4, 0)
    a.mov(2, 0)
    a.branch("mismatch", cond=1)
    a.mem(True, 0, 8, 28)
    a.cmp_reg(5, 0)
    a.mov(2, 4)
    a.branch("mismatch", cond=1)
    a.branch("verify_done")
    a.label("mismatch")
    a.mov(6, 3)
    a.mem(False, 2, 8, 32)
    a.label("verify_done")
    a.mem(False, 6, 8, 12)
    a.mem(True, 0, 8, 60)
    a.add(0, 0, 1)
    a.mem(False, 0, 8, 60)
    a.pop((1 << 4) | (1 << 5) | (1 << 6) | (1 << 15))

    a.label("paint")
    a.mem(True, 2, 8, 12)
    a.literal(1, 0x001F)
    for state, color in ((0, 0x4000), (1, 0x03E0), (2, 0x7FE0), (4, 0x03FF)):
        a.cmp(2, state)
        a.literal(0, color)
        a.mov_reg(1, 0, cond=0)
    a.literal(0, 0x06000000)
    a.literal(2, 240 * 160)
    a.label("paint_pixel")
    a.half(False, 1, 0, 2, post=True)
    a.sub(2, 2, 1, flags=True)
    a.branch("paint_pixel", cond=1)
    a.ret()

    a.label("read_all")
    if kind != "eeprom":
        a.literal(0, 0x0E000000)
        a.mov_reg(1, 9)
        a.mov_reg(2, 10)
        a.label("read_byte")
        a.mem(True, 3, 0, 1, byte=True, post=True)
        a.mem(False, 3, 1, 1, byte=True, post=True)
        a.sub(2, 2, 1, flags=True)
        a.branch("read_byte", cond=1)
        a.ret()
    else:
        a.push((1 << 4) | (1 << 5) | (1 << 14))
        a.mov(4, 0)
        a.mov_reg(5, 9)
        a.label("read_block")
        a.mov_reg(0, 4)
        a.mov_reg(1, 5)
        a.branch("eeprom_read", link=True)
        a.add(5, 5, 8)
        a.add(4, 4, 1)
        a.cmp(4, capacity // 8)
        a.branch("read_block", cond=1)
        a.pop((1 << 4) | (1 << 5) | (1 << 15))

    a.label("write_all")
    if kind == "sram":
        a.mov_reg(0, 9)
        a.literal(1, 0x0E000000)
        a.mov_reg(2, 10)
        a.label("write_byte")
        a.mem(True, 3, 0, 1, byte=True, post=True)
        a.mem(False, 3, 1, 1, byte=True, post=True)
        a.sub(2, 2, 1, flags=True)
        a.branch("write_byte", cond=1)
        a.ret()
    elif kind == "flash":
        a.push((1 << 4) | (1 << 5) | (1 << 6) | (1 << 14))
        a.mov(0, 0x80)
        a.branch("flash_command", link=True)
        a.mov(0, 0x10)
        a.branch("flash_command", link=True)
        if flash_poll:
            a.literal(1, 0x0E000000)
            a.label("flash_erase_ready")
            a.mem(True, 0, 1, byte=True)
            a.cmp(0, 0xFF)
            a.branch("flash_erase_ready", cond=1)
        a.mov_reg(4, 9)
        a.literal(5, 0x0E000000)
        a.mov_reg(6, 10)
        a.label("write_flash_byte")
        a.mov(0, 0xA0)
        a.branch("flash_command", link=True)
        a.mem(True, 3, 4, 1, byte=True, post=True)
        if flash_poll:
            a.mem(False, 3, 5, byte=True)
            a.label("flash_program_ready")
            a.mem(True, 0, 5, byte=True)
            a.cmp_reg(0, 3)
            a.branch("flash_program_ready", cond=1)
            a.add(5, 5, 1)
        else:
            a.mem(False, 3, 5, 1, byte=True, post=True)
        a.sub(6, 6, 1, flags=True)
        a.branch("write_flash_byte", cond=1)
        if flash_poll:
            # This core's Flash busy status remains attached to sector zero
            # after chip erase. Check that sector before reading the image.
            a.literal(1, 0x0E000000)
            a.mem(True, 3, 9, byte=True)
            a.label("flash_image_ready")
            a.mem(True, 0, 1, byte=True)
            a.cmp_reg(0, 3)
            a.branch("flash_image_ready", cond=1)
        a.pop((1 << 4) | (1 << 5) | (1 << 6) | (1 << 15))
        a.label("flash_command")
        a.literal(1, 0x0E005555)
        a.mov(2, 0xAA)
        a.mem(False, 2, 1, byte=True)
        a.literal(1, 0x0E002AAA)
        a.mov(2, 0x55)
        a.mem(False, 2, 1, byte=True)
        a.literal(1, 0x0E005555)
        a.mem(False, 0, 1, byte=True)
        a.ret()
    else:
        a.push((1 << 4) | (1 << 5) | (1 << 14))
        a.mov(4, 0)
        a.mov_reg(5, 9)
        a.label("write_block")
        a.mov_reg(0, 4)
        a.mov_reg(1, 5)
        a.branch("eeprom_write", link=True)
        a.add(5, 5, 8)
        a.add(4, 4, 1)
        a.cmp(4, capacity // 8)
        a.branch("write_block", cond=1)
        a.pop((1 << 4) | (1 << 5) | (1 << 15))

    if kind == "eeprom" and eeprom_dma:
        _eeprom_dma(a)
    if kind == "eeprom" and not eeprom_dma:
        for reading in (True, False):
            prefix = "eeprom_read" if reading else "eeprom_write"
            a.label(prefix)
            a.push(sum(1 << r for r in (4, 5, 6, 7, 14)))
            a.mov_reg(6, 0)
            a.mov_reg(5, 1)
            a.literal(4, 0x0DFFFF00)
            a.mov(0, 1)
            a.half(False, 0, 4)
            a.mov(0, int(reading))
            a.half(False, 0, 4)
            a.mov(7, 5)
            a.label(prefix + "_address")
            a.mov_reg(0, 6, shift_type=1, shift_reg=7)
            a.dp(0, 0, 0, 1, immediate=True)
            a.half(False, 0, 4)
            a.sub(7, 7, 1, flags=True)
            a.branch(prefix + "_address", cond=5)  # PL
            if reading:
                a.mov(0, 0)
                a.half(False, 0, 4)
                for _ in range(4):
                    a.half(True, 0, 4)
            a.mov(6, 8)
            a.label(prefix + "_byte")
            if reading:
                a.mov(2, 0)
            else:
                a.mem(True, 2, 5, 1, byte=True, post=True)
            a.mov(3, 8)
            a.label(prefix + "_bit")
            if reading:
                a.half(True, 0, 4)
                a.dp(0, 0, 0, 1, immediate=True)
                a.mov_reg(2, 2, shift=1)
                a.dp(12, 2, 2, 0)
            else:
                a.mov_reg(0, 2, shift=7, shift_type=1)
                a.dp(0, 0, 0, 1, immediate=True)
                a.half(False, 0, 4)
                a.mov_reg(2, 2, shift=1)
            a.sub(3, 3, 1, flags=True)
            a.branch(prefix + "_bit", cond=1)
            if reading:
                a.mem(False, 2, 5, 1, byte=True, post=True)
            a.sub(6, 6, 1, flags=True)
            a.branch(prefix + "_byte", cond=1)
            if not reading:
                a.mov(0, 0)
                a.half(False, 0, 4)
                a.label(prefix + "_ready")
                a.half(True, 0, 4)
                a.dp(8, 0, 0, 1, immediate=True, flags=True)
                a.branch(prefix + "_ready", cond=0)
            a.pop(sum(1 << r for r in (4, 5, 6, 7, 15)))

    code = a.finish()
    rom = bytearray([0xFF] * 32768)
    struct.pack_into("<I", rom, 0, 0xEA00002E)
    rom[0xA0:0xAC] = ("SAVE " + kind.upper()).ljust(12).encode("ascii")
    rom[0xAC:0xB2] = ("XS%02d00" % kind_id).encode("ascii")
    rom[0xB2] = 0x96
    rom[0xBD] = (-sum(rom[0xA0:0xBD]) - 0x19) & 255
    assert len(code) <= len(rom) - 0xC0
    rom[0xC0:0xC0 + len(code)] = code
    return bytes(rom)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("build/save-test-roms"))
    parser.add_argument("--kind", action="append", choices=KINDS)
    parser.add_argument("--eeprom-dma", action="store_true",
                        help="Use hardware DMA3 transactions for the EEPROM diagnostic only")
    parser.add_argument("--flash-poll", action="store_true",
                        help="Wait for Flash erase/program completion before continuing")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    for kind in args.kind or KINDS:
        path = args.output / ("__save_" + kind + ".gba")
        data = save_test_rom(kind, eeprom_dma=args.eeprom_dma, flash_poll=args.flash_poll)
        path.write_bytes(data)
        print(f"{path}: {len(data)} byte ROM, {KINDS[kind][1]} byte battery image")


