"""Generate the GPL-2.0-or-later handheld UI font from bundled GNU Unifont.

The source is third_party/ReGBA/source/tools/unifont.hex.gz. Its provenance
and GPL v2-or-later notice are in third_party/ReGBA/doc/copyright_en.txt.
Include every BMP glyph available in that source so ROM filenames can use
common simplified/traditional Chinese and other covered scripts. This older
source contains all GB2312 and Big5 Han characters, but has BMP gaps and no
CJK Extension A. Missing filename glyphs retain the renderer's replacement
box. Printable ASCII and --text UI labels are required; missing label glyphs
remain a build error.
"""
import argparse
import gzip
from pathlib import Path


def make_header(source, text_files):
    requested = set(range(0x20, 0x7f))
    for text_file in text_files:
        requested.update(ord(char) for char in text_file.read_text(
            encoding='utf-8-sig') if ord(char) >= 0x80)
    glyphs = {}
    opener = gzip.open if source.suffix == '.gz' else open
    with opener(source, 'rt', encoding='ascii') as stream:
        for line in stream:
            code, bitmap = line.strip().split(':', 1)
            codepoint = int(code, 16)
            if codepoint > 0xffff and codepoint not in requested:
                continue
            if len(bitmap) not in (32, 64):
                raise ValueError(f'U+{codepoint:04X}: expected an 8x16 or 16x16 glyph')
            width = len(bitmap) // 4
            row_digits = width // 4
            rows = [int(bitmap[pos:pos + row_digits], 16) << (16 - width)
                    for pos in range(0, len(bitmap), row_digits)]
            glyphs[codepoint] = (width, rows)
    missing = sorted(requested - glyphs.keys())
    if missing:
        raise ValueError('missing Unifont glyphs: ' + ', '.join(
            f'U+{codepoint:04X}' for codepoint in missing))

    lines = [
        '/* Generated by scripts/prepare-ui-font.py; do not edit.',
        ' * GNU Unifont (C) 2000 Roman Czyborra. GPL-2.0-or-later.',
        ' * Source: third_party/ReGBA/source/tools/unifont.hex.gz.',
        ' * License: third_party/ReGBA/doc/copyright_en.txt.',
        ' * Includes every BMP glyph available in the bundled source.',
        ' */',
        '#ifndef REGBA_UI_FONT_H',
        '#define REGBA_UI_FONT_H',
        '#include <stdint.h>',
        'typedef struct {',
        '    uint32_t codepoint;',
        '    uint16_t rows[16];',
        '    uint8_t width;',
        '} ui_font_glyph_t;',
        'static const ui_font_glyph_t ui_font_glyphs[] = {',
    ]
    for codepoint in sorted(glyphs):
        width, rows = glyphs[codepoint]
        values = ', '.join(f'0x{row:04x}' for row in rows)
        lines.append(f'    {{0x{codepoint:04x}, {{{values}}}, {width}}},')
    lines += [
        '};',
        '#define UI_FONT_GLYPH_COUNT (sizeof(ui_font_glyphs) / sizeof(ui_font_glyphs[0]))',
        '#endif',
        '',
    ]
    return '\n'.join(lines), len(glyphs)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--text', type=Path, action='append', default=[])
    args = parser.parse_args()
    try:
        header, count = make_header(args.source, args.text)
    except (OSError, UnicodeError, ValueError) as error:
        parser.exit(1, f'UI font generation failed: {error}\n')
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_text(encoding='ascii') != header:
        with args.output.open('w', encoding='ascii', newline='\n') as stream:
            stream.write(header)
    print(f'UI font: {count} glyphs (available BMP + required labels) -> {args.output}')


if __name__ == '__main__':
    main()
