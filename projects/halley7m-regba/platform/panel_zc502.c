static void power_on(void)
{
    command_result = 0;
    LL_GPIO_setPinMode(PC_Instance, 14, GPIO_MODE_OUTPUT0);
    LL_GPIO_setPinMode(PC_Instance, 11, GPIO_MODE_OUTPUT0);
    HAL_Delay(50);
    LL_GPIO_setPinMode(PC_Instance, 10, GPIO_MODE_OUTPUT0);
    HAL_Delay(10);
    LL_GPIO_setPinMode(PC_Instance, 10, GPIO_MODE_OUTPUT1);
    /* This HAL initializes the PHY before releasing panel reset, unlike
     * the original U-Boot. Wait explicitly before sending the first DCS. */
    HAL_Delay(120);
}

static void panel_init(void)
{
    struct dsi_cmd_packet sleep_out = {0x05, 0x11, 0x00, NULL};
    struct dsi_cmd_packet display_on = {0x05, 0x29, 0x00, NULL};

    for (unsigned i = 0; i < sizeof(commands) / sizeof(commands[0]); ++i) {
        if (dsi_write_cmd(&commands[i]) < 0) {
            command_result = -EIO;
            return;
        }
    }
    if (dsi_write_cmd(&sleep_out) < 0) {
        command_result = -EIO;
        return;
    }
    HAL_Delay(120);
    if (dsi_write_cmd(&display_on) < 0) {
        command_result = -EIO;
        return;
    }
    HAL_Delay(5);
}

int panel_zc502_result(void)
{
    return command_result;
}

void panel_zc502_backlight_on(void)
{
    LL_CPM_CGU_ConfigTypeDef clock = {
        .PLLMux = PWMCDR_SCLK_A, .Div = 2, .Config = 0
    };
    LL_PWM_InitTypeDef pwm = {
        .PreScale = 5, .InitLevel = PWM_LEVEL_LOW,
        .IdleLevel = PWM_LEVEL_LOW, .Mode = PWM_MODE_CPU
    };

    /* Preserve the working Linux register profile: PWMCDR=0x00000002,
     * PWMCC15=5 and PWMWC15=0xA6AA5356. Linux requested 1 kHz,
     * 2/3 duty; use the measured register profile without assuming frequency.
     * Never drive a full-bright intermediate state. */
    HAL_Delay(100);
    CPM_GATE_Enable(CPM_Instance, CPM_CLKID_PWM);
    if (CPM_CGU_PWM_Start(CPM_Instance, &clock) != HAL_OK) {
        command_result = -EIO;
        return;
    }
    LL_PWM_Init(15, &pwm);
    LL_PWM_Set(15, 0x5356, 0xA6AA);
    backlight_initialized = 1;
    LL_GPIO_setPinMode(PC_Instance, 14, GPIO_MODE_FUNCTION0);
    LL_PWM_Start(15);
}

void panel_zc502_power_off(void)
{
    if (backlight_initialized) {
        LL_PWM_Stop(15);
        backlight_initialized = 0;
    }
    LL_GPIO_setPinMode(PC_Instance, 14, GPIO_MODE_OUTPUT0);
    LL_GPIO_setPinMode(PC_Instance, 10, GPIO_MODE_OUTPUT0);
    LL_GPIO_setPinMode(PC_Instance, 11, GPIO_MODE_OUTPUT1);
}

